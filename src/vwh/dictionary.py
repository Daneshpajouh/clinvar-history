"""Write docs/data_dictionary.md from the live catalogue, so it cannot drift from the DDL."""

from __future__ import annotations

from vwh.db import Engine

TABLES = {
    "source_release": (
        "One row per loaded source release. status 'rolled_back'"
        " keeps an audit row after vwh unload."
    ),
    "provenance": (
        "One row per input file: URL, size, SHA-256, fetch and load times, rows staged and loaded."
    ),
    "review_status": "ClinVar review status text and its star level (0 to 4).",
    "ancestry_group": "gnomAD v4.1 genetic ancestry group codes.",
    "gene": "NCBI Gene IDs seen in ClinVar; panel genes carry Ensembl GRCh38 coordinates.",
    "variant": (
        "GRCh38 alleles keyed chrom-pos-ref-alt with VCF"
        " left-aligned alleles, shared by ClinVar and gnomAD."
    ),
    "clinvar_variation": (
        "ClinVar VariationID with its AlleleID, HGVS parts and match"
        " keys; attributes from the latest release."
    ),
    "classification": (
        "Aggregate germline record per VariationID as an SCD type 2 history across releases."
    ),
    "submitter": (
        "Submitting organisations by name (submission_summary carries no organisation ID)."
    ),
    "submission": (
        "Individual SCV records per release, kept apart from the aggregate classification."
    ),
    "population_frequency": "gnomAD v4.1 joint allele counts per variant and ancestry group.",
    "score_set": "MaveDB score sets with licence, DOI and the level used to match ClinVar.",
    "functional_score": "MaveDB variant scores with the key used to join ClinVar.",
}


def render(engine: Engine) -> str:
    out = [
        "# Data dictionary",
        "",
        "Generated by `vwh dictionary` from the DuckDB catalogue after `vwh load`."
        " Types are DuckDB names; PostgreSQL uses the equivalent types from the same migrations.",
        "",
    ]
    for table, text in TABLES.items():
        _, rows = engine.query(
            "SELECT column_name, data_type, is_nullable FROM information_schema.columns"
            " WHERE table_name = ? ORDER BY ordinal_position",
            [table],
        )
        n = engine.scalar(f"SELECT count(*) FROM {table}")
        out += [f"## {table}", "", f"{text} Rows in the build described in the README: {n:,}.", ""]
        out += ["| Column | Type | Nullable |", "| --- | --- | --- |"]
        out += [f"| {c} | {t} | {'yes' if nl == 'YES' else 'no'} |" for c, t, nl in rows]
        out.append("")
    return "\n".join(out)
